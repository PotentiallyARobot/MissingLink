"""Render public previews of reviewed synthetic QA runs (never account history).

Text previews are document renders of actual inputs/output excerpts. Generated
image bytes are copied unchanged. No provider calls or credentials are used.
"""
from pathlib import Path
import base64
import csv
import io
import json
import re
import shutil
import sys
import zipfile
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'tmp/marketplace-live-samples'
DEST=ROOT/'assets/promptflow-marketplace/samples'
DEST.mkdir(exist_ok=True)
catalog=json.loads((SOURCE/'catalog.json').read_text('utf-8'))
ledger=json.loads((SOURCE/'ledger.json').read_text('utf-8'))
font=lambda size,bold=False:ImageFont.truetype('C:/Windows/Fonts/'+('segoeuib.ttf' if bold else 'segoeui.ttf'),size)

def sheet(target,title,label,body,footer):
    canvas=Image.new('RGB',(1200,900),'#f8fafc');draw=ImageDraw.Draw(canvas)
    draw.rectangle((0,0,1200,14),fill='#167d91')
    draw.text((60,44),label.upper(),font=font(22,True),fill='#167d91')
    draw.text((60,92),title,font=font(38,True),fill='#182c3a')
    draw.line((60,155,1140,155),fill='#ced8df',width=2)
    body=re.sub(r'https://(?:www\.)?missinglink\.build/api/promptflow/\S+','[private artifact]',body)
    lines=[]
    for para in body.splitlines():
        line=''
        for word in para.split():
            candidate=(line+' '+word).strip()
            if draw.textlength(candidate,font=font(27))>1070 and line:lines.append(line);line=word
            else:line=candidate
        lines.append(line)
    for i,line in enumerate(lines[:17]):draw.text((60,185+i*34),line,font=font(27),fill='#334a59')
    draw.line((60,810,1140,810),fill='#ced8df',width=2)
    draw.text((60,838),footer+(' · Excerpt' if len(lines)>17 else ''),font=font(20),fill='#526875')
    canvas.save(target)

manifest={}
for item in catalog:
    sid=item['id'];folder=SOURCE/sid
    if ledger.get(sid,{}).get('status')!='complete':continue
    input_image=DEST/f'{sid}-input.png'
    if 'image' not in item['input_kinds']:
        sheet(input_image,item['name'],'Sample input',item['sample_input'],'Synthetic example used in the live test')
    if not input_image.exists():raise RuntimeError('Missing source input: '+sid)
    output_image=DEST/f'{sid}-output.png'
    caption='Actual output excerpt'
    if sid in ('browser-game','website-rebrand'):
        html=(folder/'output-0-html_url.html').read_text('utf-8')
        encoded=re.search(r'data:image/png;base64,([A-Za-z0-9+/=]+)',html)
        if not encoded:raise RuntimeError('Missing embedded artwork: '+sid)
        output_image.write_bytes(base64.b64decode(encoded[1]))
        caption='Generated artwork embedded in the '+('playable HTML game' if sid=='browser-game' else 'downloadable website')
        if sid=='browser-game' and (folder/'sample-canvas.png').exists():
            shutil.copyfile(folder/'sample-canvas.png',output_image)
            caption='Actual game canvas after six seconds of play'
    elif list(folder.glob('image-*.png')):
        images=sorted(folder.glob('image-*.png'))
        # Product review contains the uploaded input first, generated output second.
        shutil.copyfile(images[-1] if sid=='product-scene' else images[0],output_image)
        caption='Actual generated image from this run'
    elif list(folder.glob('*.png')):
        shutil.copyfile(sorted(folder.glob('*.png'))[0],output_image)
        caption='Actual generated image from this run'
    else:
        packs=list(folder.glob('*.zip'))
        if not packs:raise RuntimeError('No reviewable output: '+sid)
        with zipfile.ZipFile(packs[0]) as pack:
            names=pack.namelist()
            first=next((n for n in names if n.endswith('.csv')),next((n for n in names if n.endswith('.md')),names[0]))
            content=pack.read(first).decode('utf-8')
            if first.endswith('.csv'):
                records=list(csv.DictReader(io.StringIO(content)))
                content='\n\n'.join('\n'.join(f'{key}: {value}' for key,value in row.items()) for row in records)
            body='Files: '+', '.join(names)+'\n\n'+content
        sheet(output_image,item['name'],'Actual run output',body,'Generated by the downloadable workflow · 12 November 2026')
    manifest[sid]={'input_image':f'/assets/promptflow-marketplace/samples/{sid}-input.png',
                   'output_image':f'/assets/promptflow-marketplace/samples/{sid}-output.png',
                   'output_caption':caption,'date':'2026-11-12','source':'Live workflow run with synthetic input'}
(DEST/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
if '--backend' in sys.argv:
    backend=Path(sys.argv[sys.argv.index('--backend')+1]).resolve()
    (backend/'src/promptflow_marketplace_samples.ts').write_text('// Reviewed synthetic examples; no personal run URLs or identifiers.\nexport const MARKETPLACE_SAMPLES: Record<string, any> = '+json.dumps(manifest,indent=2)+';\n',encoding='utf-8')
print('Rendered',len(manifest),'sample pairs from completed runs.')
